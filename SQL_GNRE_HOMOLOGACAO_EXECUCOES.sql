-- GNRE — trilha de idempotência/auditoria de homologação.
-- Executar no Supabase somente após aprovação; não aplicado automaticamente.
-- Acesso exclusivo do backend (service role); sem políticas para anon/authenticated.

create table if not exists public.gnre_homologacao_execucoes (
  id bigint generated by default as identity primary key,
  chave_idempotencia text not null unique,
  servico text not null check (servico in ('consulta')),
  recibo_mascarado text not null,
  ator text,
  estado text not null check (estado in ('reservado','enviando','concluido','falha','resultado_incerto')),
  tentativa integer not null default 1 check (tentativa >= 1),
  http_status integer,
  categoria text,
  erro_codigo text,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create index if not exists gnre_homologacao_execucoes_estado_idx
  on public.gnre_homologacao_execucoes (estado, criado_em desc);

alter table public.gnre_homologacao_execucoes enable row level security;

revoke all on public.gnre_homologacao_execucoes from anon, authenticated;

comment on table public.gnre_homologacao_execucoes is
  'Idempotência/auditoria GNRE. Não armazenar XML, recibo completo, senha ou PFX.';
